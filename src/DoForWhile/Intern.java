package DoForWhile;

public class Intern {

    public static void main(String[] args) {

        for (int a = 1; a <= 10; a++) {
            System.out.println("a = " + a);
        }


        int b = 0;
        do {

            b++;
            System.out.println(b);

        } while (b >= 10);


    }
}
