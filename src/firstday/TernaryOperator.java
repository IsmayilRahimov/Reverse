package firstday;

public class TernaryOperator {


    public static void main(String[] args) {

        int num = 10;

        String result = (num % 2 == 0) ? "Dogrudur" : "Yalnisdir";

        System.out.println(result);


        String result2 = (num - 5 == 0) ? "Dogrudur" : "Yalnisdir";
        System.out.println(result2);

    }
}
